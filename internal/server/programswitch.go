// programsNow reads the switch now (a broken config.toml still gives
// its tables; none at all is off).
func programsNow() bool {
	cfg, _ := config.Load()
	return features.Programs(cfg)
}

// recordBoots reads the settings once and says, per recorded session,
// whether it runs at a server start: a coordinator or thread while its
// project is active and not archived (projectBoots), a director while
// programs are on, anything else always.
func recordBoots() func(r SessionRecord) bool {
	boots, on := projectBoots(), programsNow()
	return func(r SessionRecord) bool {
		switch {
		case r.Role == proto.RoleDirector:
			return on
		case dormantRole(r):
			return boots(r.Project)
		}
		return true
	}
}

// directorGone says why a dormant director is no longer to be resumed:
// its program was deleted, or a project has its name now (§3.4); ""
// when it still is.
func directorGone(r SessionRecord) string {
	g, err := program.Open(r.Project, nil)
	switch {
	case err != nil:
		return "its program is gone"
	case g.LeftOut:
		return "a project has its program's name"
	}
	return ""
}

// backOnPrompt is a resumed director's one nudge: programs are back on,
// and what its program's children did while they were off, by the
// actions in their journals (tm's words only, never an agent's).
func backOnPrompt(slug string, since time.Time) string {
	var b strings.Builder
	b.WriteString("[tm] Programs are back on")
	if !since.IsZero() {
		fmt.Fprintf(&b, " (off since %s)", since.UTC().Format(time.RFC3339))
	}
	b.WriteString(". ")
	var lines []string
	if g, err := program.Open(slug, nil); err == nil {
		for _, m := range g.Members {
			if strings.Contains(m, "/") {
				continue // a paired server's: not in this server's journals
			}
			lines = append(lines, m+": "+journalSince(m, since))
		}
	}
	if len(lines) == 0 {
		b.WriteString("Your program has no projects on this server.")
	} else {
		b.WriteString("While they were off, your children's journals show: " + strings.Join(lines, "; ") + ".")
	}
	b.WriteString(" Read tm program context, then the children's journals for the details. (Generated by tm.)")
	return b.String()
}

// journalSince counts project slug's journal actions from since on (to
// the second, the journal's precision): "3 task.add, 1 thread.start",
// or "nothing".
func journalSince(slug string, since time.Time) string {
	since = since.Truncate(time.Second)
	p, err := project.Open(slug)
	if err != nil {
		return "not readable"
	}
	lines, _, err := p.JournalTail(1 << 20)
	if err != nil {
		return "not readable"
	}
	count := map[string]int{}
	for _, l := range lines {
		f := strings.Fields(l)
		if len(f) < 3 {
			continue
		}
		at, err := time.Parse(time.RFC3339, f[0])
		if err != nil || at.Before(since) {
			continue
		}
		count[f[2]]++
	}
	if len(count) == 0 {
		return "nothing"
	}
	acts := make([]string, 0, len(count))
	for a := range count {
		acts = append(acts, a)
	}
	sort.Slice(acts, func(i, j int) bool {
		if count[acts[i]] != count[acts[j]] {
			return count[acts[i]] > count[acts[j]]
		}
		return acts[i] < acts[j]
	})
	parts := make([]string, 0, len(acts))
	for _, a := range acts {
		parts = append(parts, fmt.Sprintf("%d %s", count[a], a))
	}
	return strings.Join(parts, ", ")
}

// wakeRecord is a dormant record as it resumes: a director's gets the
// back-on nudge queued first (reprompt delivers it once idle).
func wakeRecord(r SessionRecord) SessionRecord {
	if r.Role != proto.RoleDirector {
		return r
	}
	nudge := session.KeptPrompt{Text: backOnPrompt(r.Project, r.Dormant), Queued: time.Now().UTC()}
	r.Queued = append([]session.KeptPrompt{nudge}, r.Queued...)
	r.Dormant = time.Time{}
	return r
}

// setPrograms is programs.switch: the human turns programs on or off.
// The setting is written first, so a server start in between does what
// it says; then the directors go dormant or resume (applyPrograms).
// Doing it again does what is left.
func (s *Server) setPrograms(p proto.ProgramsSwitchParams, c caller.Caller) (any, *proto.Error) {
	if c.IsAgent() {
		return nil, proto.Errorf("human-only", "the user turns programs on and off, in Settings → all projects → Features")
	}
	cfg, _ := config.Load()
	res := proto.ProgramsSwitchResult{Changed: features.Programs(cfg) != p.On}
	if res.Changed {
		if err := config.Set(features.Table, features.Key, p.On); err != nil {
			return nil, codeErr(err)
		}
		journalPrograms(c, p.On)
	}
	res.Stopped, res.Resumed, res.Lost = s.applyPrograms(p.On)
	s.log.Printf("programs.switch %v: changed %v, stopped %v, resumed %v, lost %v", p.On, res.Changed, res.Stopped, res.Resumed, res.Lost)
	return res, nil
}

// journalPrograms writes the switch into every program's journal, so
// the program's history says when it was dormant.
func journalPrograms(c caller.Caller, on bool) {
	list, _ := program.List(nil)
	for _, sum := range list {
		if g, err := program.Open(sum.Slug, nil); err == nil {
			_ = g.Journal(c, "features.programs", sum.Slug, onOffWord(on))
		}
	}
}

func onOffWord(on bool) string {
	if on {
		return "on"
	}
	return "off"
}

// programsMu keeps applyPrograms to one at a time: the switch's method
// and the sweep's check may meet.
var programsMu sync.Mutex

// applyPrograms makes the sessions and the links match the switch: off
// stops the running directors into dormant records, releases the
// thread slots held for them (the waiters they held go back to the
// plain line), pauses the program outbox and leaves the link hello cap
// "program" out; on lists the cap again, lets the outbox go on, resumes
// the dormant directors, each with the back-on nudge, and asks the
// ticker for a sweep, which recomputes the cross-project dependency
// states and raises the dep-ready items owed since the switch-off
// (sweepDeps).
func (s *Server) applyPrograms(on bool) (stopped, resumed, lost []string) {
	programsMu.Lock()
	defer programsMu.Unlock()
	return s.applyProgramsLocked(on)
}

// applyProgramsLocked is applyPrograms, programsMu held.
func (s *Server) applyProgramsLocked(on bool) (stopped, resumed, lost []string) {
	link.SetPrograms(on)
	s.peers.SetPrograms(on)
	if !on {
		stopped = s.sleepDirectors()
		if names, err := thread.ReleaseDirectors(); err != nil || len(names) > 0 {
			s.log.Printf("programs off: released the slots held for %v (%v)", names, err)
		}
		return stopped, nil, nil
	}
	link.Kick() // what waited goes now, or shows as expired
	resumed, lost = s.wakeDirectors()
	if s.tick != nil {
		s.tick.Kick()
	}
	return nil, resumed, lost
}

// checkPrograms is the sweep's look at the switch, for a config.toml
// edited by hand: the sessions are made to match it when they don't,
// in the background, so the sweep never waits on a director's stop. It
// leaves alone a switch already being applied.
func (s *Server) checkPrograms() {
	on := programsNow()
	s.mu.Lock()
	differs := link.ProgramsOn() != on || s.peers != nil && s.peers.Programs() != on
	for id, sess := range s.sessions {
		if r := s.records[id]; r.Role == proto.RoleDirector && !on && sess.ExitStatus() == "" && !s.sleeping[id] {
			differs = true
		}
	}
	for _, r := range s.dormant {
		if r.Role == proto.RoleDirector && on {
			differs = true
		}
	}
	s.mu.Unlock()
	if !differs || !programsMu.TryLock() {
		return
	}
	go func() {
		defer programsMu.Unlock()
		stopped, resumed, lost := s.applyProgramsLocked(programsNow())
		s.log.Printf("programs %s in config.toml: stopped %v, resumed %v, lost %v", onOffWord(on), stopped, resumed, lost)
	}()
}

// sleepDirectors stops the running directors, keeping their records
// dormant, and names them.
func (s *Server) sleepDirectors() (names []string) {
	s.mu.Lock()
	var stop []func()
	for id, sess := range s.sessions {
		r := s.records[id]
		if r.Role != proto.RoleDirector || sess.ExitStatus() != "" || s.sleeping[id] {
			continue
		}
		s.sleeping[id] = true
		names = append(names, restartLabel(r))
		stop = append(stop, func() { sess.Stop(StopGrace) })
	}
	s.mu.Unlock()
	var wg sync.WaitGroup
	for _, f := range stop {
		wg.Go(f)
	}
	wg.Wait()
	slices.Sort(names)
	return names
}

// wakeDirectors resumes the dormant directors, each told programs are
// back on. One whose program is gone, or left out, is dropped.
func (s *Server) wakeDirectors() (resumed, lost []string) {
	s.mu.Lock()
	var wake []SessionRecord
	for id, r := range s.dormant {
		if r.Role != proto.RoleDirector {
			continue
		}
		delete(s.dormant, id)
		if why := dormantGone(r); why != "" {
			s.log.Printf("session %s: dormant %s dropped: %s", id, restartLabel(r), why)
			continue
		}
		if _, live := s.sessions[id]; live {
			continue
		}
		wake = append(wake, wakeRecord(r))
	}
	s.mu.Unlock()
	for _, r := range wake {
		if o := s.resumeOne(r); o.how == "lost" {
			lost = append(lost, restartLabel(r))
		} else {
			resumed = append(resumed, restartLabel(r))
		}
	}
	s.mu.Lock()
	if err := s.saveLocked(""); err != nil {
		s.log.Printf("sessions.json: %v", err)
	}
	s.mu.Unlock()
	slices.Sort(resumed)
	slices.Sort(lost)
	return resumed, lost
}
