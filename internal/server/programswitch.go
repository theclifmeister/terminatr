package server

// The programs switch (the programs design §3.5): [features] programs,
// off by default. Off, no director runs: switching off stops the
// running directors into dormant records, kept with their conversation
// as a deactivated project's coordinator is (active.go); switching back
// on resumes them, each told once what its children did meanwhile. The
// human switches it in the TUI (programs.switch); a hand edit of
// config.toml is caught at the next ticker sweep (checkPrograms).

