package server

import (
	"strings"
	"time"

	"github.com/theclifmeister/terminatr/internal/agent"
	"github.com/theclifmeister/terminatr/internal/proto"
	"github.com/theclifmeister/terminatr/internal/session"
)

// restartOutcome is what became of one session of the previous server.
type restartOutcome struct {
	rec SessionRecord
	how string // "resumed", "fresh" (relaunched with no conversation) or "lost"
	// reprompted: resumed after a turn the stop interrupted, and told to
	// carry on (reprompt).
	reprompted bool
}

// restartLabel names a session in the restart item: the thread id, the
// coordinator, "<agent> <id>" for a plain agent session, or "<role> <id>".
func restartLabel(r SessionRecord) string {
	switch {
	case r.Thread != "":
		return r.Thread
	case r.Role == proto.RoleCoordinator:
		return "coordinator"
	case r.Agent != "" && (r.Role == proto.RoleShell || r.Role == ""):
		return r.Agent + " " + r.ID
	case r.Role == "":
		return "session " + r.ID
	}
	return r.Role + " " + r.ID
}

// restartSummary is the log line: "server restarted after crash;
// resumed coordinator, t-0003; re-prompted t-0003; started fresh t-0005;
// lost shell s-12".
func restartSummary(prevShut string, outs []restartOutcome) string {
	by := map[string][]string{}
	for _, o := range outs {
		by[o.how] = append(by[o.how], restartLabel(o.rec))
		if o.reprompted {
			by["reprompted"] = append(by["reprompted"], restartLabel(o.rec))
		}
	}
	head := "server restarted"
	if prevShut == "crash" {
		head = "server restarted after crash"
	}
	parts := []string{head}
	for _, k := range []struct{ how, verb string }{{"resumed", "resumed"}, {"reprompted", "re-prompted"}, {"fresh", "started fresh"}, {"lost", "lost"}} {
		if l := by[k.how]; len(l) > 0 {
			parts = append(parts, k.verb+" "+strings.Join(l, ", "))
		}
	}
	return strings.Join(parts, "; ")
}

// logRestart logs what became of each session of the previous server,
// by name. The per-project inbox item is the ticker's (ServerRestarted).
func (s *Server) logRestart(prevShut string, outs []restartOutcome) {
	if len(outs) > 0 {
		s.log.Printf("%s", restartSummary(prevShut, outs))
	}
}

// interruptedPrompt is what a session stopped mid-turn by the previous
// server is told once resumed and idle.
const interruptedPrompt = "[tm] The tm server restarted (tm update or tm server restart) while you were working, which interrupted your turn. Carry on where you left off: check what your last steps did before you redo any. (Generated by tm.)"

// interruptedWait bounds how long a resumed session may take to come up
// idle before its re-prompt is given up.
const interruptedWait = 10 * time.Minute

// markInterrupted marks the records of the agents working on a turn,
// or blocked within one, as sessions stops them: the next server
// re-prompts them (reprompt). s.mu not held.
func (s *Server) markInterrupted(sessions []*session.Session) {
	var mid []string
	for _, sess := range sessions {
		if st, ok := sess.AgentState(); ok && worked(st) {
			mid = append(mid, sess.ID())
		}
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	for _, id := range mid {
		if r, ok := s.records[id]; ok && r.Agent != "" {
			r.Interrupted = true
			s.records[id] = r
		}
	}
}

// reprompt tells a session resumed after an interrupted turn to carry
// on, once it is idle: a prompt sent before the resumed agent is up
// could reach a conversation it hasn't loaded yet. It gives up when the
// session ends or stays busy for interruptedWait.
func (s *Server) reprompt(sess *session.Session) {
	deadline := time.After(interruptedWait)
	for {
		ch := sess.StateChanged()
		st, ok := sess.AgentState()
		if !ok || st.State == agent.StateExited {
			return
		}
		if st.State == agent.StateIdle {
			if _, perr := s.promptWith(proto.SessionPromptParams{ID: sess.ID(), Text: interruptedPrompt}, session.PromptOptions{Channel: true}); perr != nil {
				s.log.Printf("session %s: re-prompt after the restart: %s", sess.ID(), perr.Message)
			}
			return
		}
		select {
		case <-ch:
		case <-sess.Done():
			return
		case <-deadline:
			s.log.Printf("session %s: not re-prompted after the restart: still %s after %s", sess.ID(), st.State, interruptedWait)
			return
		}
	}
}
