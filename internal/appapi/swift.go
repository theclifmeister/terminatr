package appapi

import (
	"fmt"
	"slices"
	"strings"
)

// Swift is the Mac app's Codable types, generated from the Schema
// (macos/Sources/TerminatrKit/AppAPI.swift; `go test ./internal/appapi
// -update` rewrites it). Every type in $defs but the envelope's (the
// app's bridge client reads and writes those lines itself) becomes a
// struct nested in the AppAPI namespace, so Task, Thread and Error don't
// shadow Swift's. A field the Go side omits when empty (omitempty) gets
// its zero value when absent, as in Go, except a struct or a time,
// which is optional; an array or a map is empty when absent or null.
// A type with an id, but no params type, is Identifiable.
// Each method becomes a descriptor in AppAPI.Methods: a Call, or a
// Subscription for a stream, naming its params, result and events'
// data types (macos/Sources/TerminatrKit/Calls.swift).
func Swift(s Schema) string {
	var b strings.Builder
	b.WriteString(`// Code generated by internal/appapi (Swift, from tm app schema); DO NOT EDIT.
// Rewrite it with: go test ./internal/appapi -update

import Foundation

/// The terminatr app API (docs/SPEC.md §3.8): what tm app bridge answers.
public enum AppAPI {
`)
	fmt.Fprintf(&b, "    /// The app API version this app was generated against.\n    public static let version = %d\n", s.AppAPI)
	skip := map[string]bool{}
	for _, k := range []string{"request", "out"} {
		skip[refName(s.Envelope[k].Ref)] = true
	}
	names := make([]string, 0, len(s.Defs))
	for n := range s.Defs {
		if !skip[n] {
			names = append(names, n)
		}
	}
	slices.Sort(names)
	for _, n := range names {
		swiftStruct(&b, n, s.Defs[n])
	}
	b.WriteString("\n    /// Every method of the app API, by name.\n    public enum Methods {\n")
	methods := make([]string, 0, len(s.Methods))
	for n := range s.Methods {
		methods = append(methods, n)
	}
	slices.Sort(methods)
	for _, n := range methods {
		m := s.Methods[n]
		params := "NoParams"
		if m.Params != nil {
			params = swiftType(*m.Params)
		}
		switch {
		case m.Stream:
			fmt.Fprintf(&b, "        public static let %s = Subscription<%s, %s, %s>(%q, events: %s)\n",
				lowerCamel(n), params, swiftType(m.Result), swiftType(*m.Data), n, swiftStrings(m.Events))
		case m.Target != "":
			fmt.Fprintf(&b, "        public static let %s = Call<%s, %s>(%q, write: %t, target: %q)\n",
				lowerCamel(n), params, swiftType(m.Result), n, m.Write, m.Target)
		default:
			fmt.Fprintf(&b, "        public static let %s = Call<%s, %s>(%q, write: %t)\n",
				lowerCamel(n), params, swiftType(m.Result), n, m.Write)
		}
	}
	b.WriteString("    }\n}\n")
	for _, n := range names {
		swiftDecoder(&b, n, s.Defs[n])
	}
	return b.String()
}

type swiftField struct {
	key, name, typ string
	// qtyp is typ with its refs qualified, for the extensions.
	qtyp string
	// zero is the value an absent field takes ("" for none: it's
	// required, or optional).
	zero     string
	optional bool
}

func swiftFields(d JSONSchema) []swiftField {
	var fs []swiftField
	for _, k := range d.Order {
		p := d.Properties[k]
		f := swiftField{key: k, name: lowerCamel(k), typ: swiftType(p), qtyp: swiftTypeIn(p, "AppAPI.")}
		required := slices.Contains(d.Required, k)
		zero := swiftZero(p)
		switch {
		case p.Type == "array" || p.Type == "object":
			f.zero = zero // null or absent: empty
		case !required && zero == "":
			f.optional = true
		case !required:
			f.zero = zero
		}
		fs = append(fs, f)
	}
	return fs
}

func swiftStruct(b *strings.Builder, name string, d JSONSchema) {
	fs := swiftFields(d)
	protos := "Codable, Sendable, Hashable"
	if !strings.HasSuffix(name, "Params") && slices.ContainsFunc(fs, func(f swiftField) bool { return f.key == "id" && !f.optional }) {
		protos += ", Identifiable"
	}
	fmt.Fprintf(b, "\n    public struct %s: %s {\n", name, protos)
	var params []string
	for _, f := range fs {
		t := f.typ
		if f.optional {
			t += "?"
		}
		fmt.Fprintf(b, "        public var %s: %s\n", swiftIdent(f.name), t)
		p := swiftIdent(f.name) + ": " + t
		switch {
		case f.optional:
			p += " = nil"
		case f.zero != "":
			p += " = " + f.zero
		}
		params = append(params, p)
	}
	fmt.Fprintf(b, "\n        public init(%s) {\n", strings.Join(params, ", "))
	for _, f := range fs {
		fmt.Fprintf(b, "            self.%s = %s\n", f.name, swiftIdent(f.name))
	}
	b.WriteString("        }\n")
	if len(fs) > 0 {
		b.WriteString("\n        enum CodingKeys: String, CodingKey {\n")
		for _, f := range fs {
			if f.name == f.key {
				fmt.Fprintf(b, "            case %s\n", swiftIdent(f.name))
			} else {
				fmt.Fprintf(b, "            case %s = %q\n", swiftIdent(f.name), f.key)
			}
		}
		b.WriteString("        }\n")
	}
	b.WriteString("    }\n")
}

// swiftDecoder is name's init(from:), in an extension so the struct
// keeps its memberwise init: absent fields take their zero value. A
// struct without fields keeps the synthesized one.
func swiftDecoder(b *strings.Builder, name string, d JSONSchema) {
	fs := swiftFields(d)
	if len(fs) == 0 {
		return // the synthesized one
	}
	fmt.Fprintf(b, "\nextension AppAPI.%s {\n    public init(from decoder: any Decoder) throws {\n", name)
	b.WriteString("        let c = try decoder.container(keyedBy: CodingKeys.self)\n")
	for _, f := range fs {
		switch {
		case f.optional:
			fmt.Fprintf(b, "        self.%s = try c.decodeIfPresent(%s.self, forKey: .%s)\n", f.name, f.qtyp, f.name)
		case f.zero != "":
			fmt.Fprintf(b, "        self.%s = try c.decodeIfPresent(%s.self, forKey: .%s) ?? %s\n", f.name, f.qtyp, f.name, f.zero)
		default:
			fmt.Fprintf(b, "        self.%s = try c.decode(%s.self, forKey: .%s)\n", f.name, f.qtyp, f.name)
		}
	}
	b.WriteString("    }\n}\n")
}

func swiftType(s JSONSchema) string { return swiftTypeIn(s, "") }

// swiftTypeIn is s's Swift type with refs prefixed by ns: an extension
// of a nested type doesn't see its namespace's names.
func swiftTypeIn(s JSONSchema, ns string) string {
	if s.Ref != "" {
		return ns + refName(s.Ref)
	}
	switch s.Type {
	case "string":
		switch {
		case s.Format == "date-time":
			return "Date"
		case s.ContentEncoding == "base64":
			return "Data"
		}
		return "String"
	case "integer":
		return "Int"
	case "number":
		return "Double"
	case "boolean":
		return "Bool"
	case "array":
		return "[" + swiftTypeIn(*s.Items, ns) + "]"
	case "object":
		if s.AdditionalProperties != nil {
			return "[String: " + swiftTypeIn(*s.AdditionalProperties, ns) + "]"
		}
	}
	panic(fmt.Sprintf("appapi swift: no Swift type for %+v", s))
}

// swiftZero is the zero value of s's Swift type, or "" when it has none
// worth taking (a struct, a time).
func swiftZero(s JSONSchema) string {
	switch {
	case s.Ref != "", s.Format == "date-time":
		return ""
	case s.ContentEncoding == "base64":
		return "Data()"
	}
	switch s.Type {
	case "string":
		return `""`
	case "integer", "number":
		return "0"
	case "boolean":
		return "false"
	case "array":
		return "[]"
	case "object":
		return "[:]"
	}
	return ""
}

func refName(ref string) string { return ref[strings.LastIndexByte(ref, '/')+1:] }

// lowerCamel turns a JSON key or a method name (snake_case, dotted) into
// a Swift name: needs_you is needsYou, session.list sessionList.
func lowerCamel(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '.' || r == '-' })
	for i := 1; i < len(parts); i++ {
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	return strings.Join(parts, "")
}

var swiftKeywords = map[string]bool{
	"associatedtype": true, "class": true, "deinit": true, "enum": true, "extension": true, "func": true,
	"import": true, "init": true, "inout": true, "internal": true, "let": true, "operator": true,
	"private": true, "protocol": true, "public": true, "static": true, "struct": true, "subscript": true,
	"typealias": true, "var": true, "break": true, "case": true, "continue": true, "default": true,
	"defer": true, "do": true, "else": true, "fallthrough": true, "for": true, "guard": true, "if": true,
	"in": true, "repeat": true, "return": true, "switch": true, "where": true, "while": true, "as": true,
	"catch": true, "false": true, "is": true, "nil": true, "rethrows": true, "super": true, "self": true,
	"throw": true, "throws": true, "true": true, "try": true,
}

func swiftIdent(s string) string {
	if swiftKeywords[s] {
		return "`" + s + "`"
	}
	return s
}

func swiftStrings(ss []string) string {
	q := make([]string, len(ss))
	for i, s := range ss {
		q[i] = fmt.Sprintf("%q", s)
	}
	return "[" + strings.Join(q, ", ") + "]"
}
