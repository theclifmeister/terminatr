package ticker

// Auto-clear (docs/SPEC.md §7.5, §11.2): with auto_clear on, the ticker
// clears the coordinator's conversation once its context reaches [ui]
// context_hint, but only while nothing waits on it. The project's state
// lives in files (tm context, CONTEXT.md with its Needs you), which the
// coordinator gets back after the clear, so nothing is lost. What it
// learned in the conversation and hasn't written down yet is the one
// thing a clear can lose, so the ticker first asks it to save that, and
// clears at the next idle gate.
//
// The user can ask for the same save and clear at any time (tm clear, the
// context hint's key, /saveclear in the coordinator's pane: RequestClear):
// the next sweep runs it through autoClear whatever auto_clear and the
// hint say, the project's waits and the grace before the ask aside, since
// the user is there and asked.

import (
	"fmt"
	"strconv"
	"strings"
	"time"

	"github.com/theclifmeister/terminatr/internal/caller"
	"github.com/theclifmeister/terminatr/internal/config"
	"github.com/theclifmeister/terminatr/internal/project"
	"github.com/theclifmeister/terminatr/internal/proto"
	"github.com/theclifmeister/terminatr/internal/thread"
)

// Defaults of auto-clear.
const (
	// DefaultClearGrace is how long every condition must hold, sweep
	// after sweep, before the ticker clears: a coordinator that just
	// answered the user is left a moment for the reply.
	DefaultClearGrace = 2 * time.Minute
	// DefaultClearEvery is how often the ticker clears at most, per
	// coordinator process: a clear that didn't take isn't repeated at
	// every sweep.
	DefaultClearEvery = 30 * time.Minute
)

// clearMemo is what autoClear saw of a project's coordinator.
type clearMemo struct {
	// Seen is the coordinator's session id and pid while every condition
	// held, since Ready.
	Seen  string    `json:"seen,omitempty"`
	Ready time.Time `json:"ready,omitzero"`
	// Cleared is when the ticker last cleared process ClearedID.
	ClearedID string    `json:"cleared_id,omitempty"`
	Cleared   time.Time `json:"cleared,omitzero"`
	// Asked is when the ticker asked process AskedID to save what it
	// learned, ahead of its clear.
	AskedID string    `json:"asked_id,omitempty"`
	Asked   time.Time `json:"asked,omitzero"`
	// Requested is when the user asked for a save and clear of process
	// RequestedID (RequestClear); cleared once it is done or dropped.
	RequestedID string    `json:"requested_id,omitempty"`
	Requested   time.Time `json:"requested,omitzero"`
}

// upkeepMemo is a clear whose upkeep prompt may still be due.
type upkeepMemo struct {
	// ID is the process cleared, Cleared when, and Percent its context
	// use then (-1: unknown).
	ID      string    `json:"id"`
	Cleared time.Time `json:"cleared"`
	Percent int       `json:"percent"`
}

// process is a session's id and pid: a relaunch under the same id is
// another process.
func process(s *proto.SessionInfo) string {
	return s.ID + "/" + strconv.Itoa(s.PID)
}

// RequestClear has the ticker save and clear coord, the coordinator of
// project slug, as auto-clear does (the user's tm clear): at the next
// sweep, which it asks for. The request holds for that process only, and
// for ClearEvery at most.
func (t *Ticker) RequestClear(slug string, coord proto.SessionInfo) {
	unlock := t.lockProjects(slug)
	pm := t.projectMemo(slug)
	t.mu.Lock()
	if pm.Clear == nil {
		pm.Clear = &clearMemo{}
	}
	pm.Clear.RequestedID, pm.Clear.Requested = process(&coord), t.o.Now()
	t.mu.Unlock()
	unlock()
	t.Kick()
}

// SaveText is the one line a coordinator gets before its clear: fixed
// words, who clears (auto_clear, or the user) and its context use.
func SaveText(pct int, user bool) string {
	who := "auto_clear clears"
	if user {
		who = "The user asked to clear"
	}
	return fmt.Sprintf("[tm] %s your conversation at the next idle moment (context at %d%%). Save now what you learned that CONTEXT.md, MEMORY.md and memory/ don't hold yet, as your own short summary, then stop; nothing else. (Generated by tm.)", who, pct)
}

// UpkeepText is the one line a coordinator gets after a clear when
// context files are over their budgets (project.Oversized): fixed words
// naming each, and two passes besides merging: version-specific facts
// checked against today, and gotchas for a doc comment listed as
// candidates for a code task.
func UpkeepText(over []project.Oversize) string {
	var files []string
	for _, o := range over {
		files = append(files, strings.TrimSuffix(o.String(), ": consolidate it"))
	}
	return fmt.Sprintf("[tm] Upkeep after the clear: %s. Consolidate them: merge overlapping notes, drop repeated, stale or fixed facts, keep each fact once, so each fits its budget. Check version-specific facts (agent versions, flakes) against today's versions and main, and drop the dead ones. List the gotchas that belong in a package's doc comment as candidates for a code task, to file as any task; don't move text into code here. Then stop, nothing else. (Generated by tm.)", strings.Join(files, "; "))
}

// autoClear clears the project's coordinator when auto_clear is on and
// its context is at or past hint percent of its window, only while it is
// idle with no prompt queued and no question open, its inbox is empty,
// and no thread waits on a question (an open menu, a needs-you, a
// blocked agent); every condition must hold for ClearGrace, and one
// process is cleared at most once per ClearEvery. Never while paused.
// The gate passing first pastes SaveText (journaled as ticker
// coordinator.clear.ask); the clear comes the next time it passes, once
// ClearGrace has gone by since the ask, journaled as ticker
// coordinator.clear. An ask older than ClearEvery is asked again.
//
// A request of the user's (RequestClear) for the running process takes
// the same steps, setting or pause aside: its gate is the coordinator's
// own (idle, nothing queued, no question), the ask goes out at once, and
// the clear follows once the coordinator rested ClearGrace after it.
func (t *Ticker) autoClear(p *project.Project, sessions []proto.SessionInfo, safety config.Safety, hint int, now time.Time) {
	pm := t.projectMemo(p.Slug)
	cm := pm.Clear
	user := false
	if cm != nil && cm.RequestedID != "" {
		coord := proto.CoordinatorOf(sessions, p.Slug)
		user = coord != nil && process(coord) == cm.RequestedID && now.Sub(cm.Requested) < t.o.ClearEvery
		if !user {
			t.o.Log.Printf("ticker: %s: save and clear of %s dropped: not done before the coordinator ended or ClearEvery went by", p.Slug, cm.RequestedID)
			cm.RequestedID, cm.Requested = "", time.Time{}
		}
	}
	if !user && (!safety.AutoClear || safety.Paused || hint <= 0) {
		pm.Clear = nil
		return
	}
	if cm == nil {
		cm = &clearMemo{}
		pm.Clear = cm
	}
	gate := hint
	if user {
		gate = 0
	}
	coord, why := clearBlocked(p, sessions, gate, false, user)
	if why != "" {
		cm.Seen, cm.Ready = "", time.Time{}
		return
	}
	// A relaunch under the same id is a new process: its grace starts
	// again.
	seen := process(coord)
	if cm.Seen != seen {
		cm.Seen, cm.Ready = seen, now
	}
	var asked bool
	if user {
		asked = cm.AskedID == seen && !cm.Asked.Before(cm.Requested)
	} else {
		asked = cm.AskedID == seen && now.Sub(cm.Asked) < t.o.ClearEvery
	}
	// The user's ask goes out at once: they just asked.
	if (!user || asked) && now.Sub(cm.Ready) < t.o.ClearGrace {
		return
	}
	if !user && cm.ClearedID == seen && now.Sub(cm.Cleared) < t.o.ClearEvery {
		return
	}
	// Delivery is at once for an idle coordinator with nothing queued;
	// still checks again anyway, so a clear never lands on new work.
	still := func() bool {
		_, why := clearBlocked(p, t.o.Host.Sessions(), gate, true, user)
		return why == ""
	}
	pct := coord.ContextPercent()
	at := fmt.Sprintf("at %d%% of its context window (hint %d%%)", pct, hint)
	if user {
		at = fmt.Sprintf("at %d%% of its context window, on the user's request", pct)
	}
	if !asked {
		if err := t.o.Host.AskSave(coord.ID, SaveText(pct, user), still); err != nil {
			t.o.Log.Printf("ticker: %s: auto-clear %s: %v", p.Slug, coord.ID, err)
			// As a failed clear: an agent without a clear isn't asked.
			cm.ClearedID, cm.Cleared = seen, now
			cm.RequestedID, cm.Requested = "", time.Time{}
			return
		}
		cm.AskedID, cm.Asked = seen, now
		detail := fmt.Sprintf("%s %s: asked to save what it learned before the clear", coord.ID, at)
		if err := p.Journal(caller.Caller{Kind: caller.Ticker}, "coordinator.clear.ask", p.Slug, detail); err != nil {
			t.o.Log.Printf("ticker: %s: journal: %v", p.Slug, err)
		}
		t.o.Log.Printf("ticker: %s: auto-clear: %s", p.Slug, detail)
		return
	}
	// The ask's turn sets the grace going again; one that ended between
	// two sweeps is waited for from the ask.
	if now.Sub(cm.Asked) < t.o.ClearGrace {
		return
	}
	cm.RequestedID, cm.Requested = "", time.Time{}
	if err := t.o.Host.Clear(coord.ID, still); err != nil {
		t.o.Log.Printf("ticker: %s: auto-clear %s: %v", p.Slug, coord.ID, err)
		// Not tried again before ClearEvery: an agent without a clear
		// stays without one.
		cm.ClearedID, cm.Cleared = seen, now
		return
	}
	cm.ClearedID, cm.Cleared = seen, now
	cm.Seen, cm.Ready = "", time.Time{}
	cm.AskedID, cm.Asked = "", time.Time{}
	pm.Upkeep = &upkeepMemo{ID: seen, Cleared: now, Percent: pct}
	detail := fmt.Sprintf("%s %s, idle with nothing waiting", coord.ID, at)
	if err := p.Journal(caller.Caller{Kind: caller.Ticker}, "coordinator.clear", p.Slug, detail); err != nil {
		t.o.Log.Printf("ticker: %s: journal: %v", p.Slug, err)
	}
	t.o.Log.Printf("ticker: %s: auto-clear: %s", p.Slug, detail)
}

// upkeepAfterClear pastes UpkeepText into the coordinator the ticker
// last cleared, once: when the clear took (its context use is below what
// it was, or unknown), it rested ClearGrace since, it is idle with
// nothing queued and no question open, and some context files are over
// their budgets; journaled as ticker coordinator.upkeep. The prompt is
// dropped when nothing is over, while paused, for another process, and
// once ClearEvery went by since the clear.
func (t *Ticker) upkeepAfterClear(p *project.Project, sessions []proto.SessionInfo, safety config.Safety, now time.Time) {
	pm := t.projectMemo(p.Slug)
	um := pm.Upkeep
	if um == nil {
		return
	}
	if safety.Paused || now.Sub(um.Cleared) >= t.o.ClearEvery {
		pm.Upkeep = nil
		return
	}
	// The coordinator's own gate, its context use aside (hint -1).
	coord, why := clearBlocked(p, sessions, -1, false, true)
	if coord == nil {
		return
	}
	if process(coord) != um.ID {
		pm.Upkeep = nil
		return
	}
	if pct := coord.ContextPercent(); why != "" || (pct >= 0 && pct >= um.Percent) || now.Sub(um.Cleared) < t.o.ClearGrace {
		return
	}
	pm.Upkeep = nil
	over, err := p.Oversized()
	if err != nil {
		t.o.Log.Printf("ticker: %s: upkeep: %v", p.Slug, err)
		return
	}
	if len(over) == 0 {
		return
	}
	still := func() bool {
		c, why := clearBlocked(p, t.o.Host.Sessions(), -1, true, true)
		return why == "" && process(c) == um.ID
	}
	if err := t.o.Host.AskSave(coord.ID, UpkeepText(over), still); err != nil {
		t.o.Log.Printf("ticker: %s: upkeep %s: %v", p.Slug, coord.ID, err)
		return
	}
	var files []string
	for _, o := range over {
		files = append(files, o.File)
	}
	detail := fmt.Sprintf("%s after its clear: asked to consolidate %s", coord.ID, strings.Join(files, ", "))
	if err := p.Journal(caller.Caller{Kind: caller.Ticker}, "coordinator.upkeep", p.Slug, detail); err != nil {
		t.o.Log.Printf("ticker: %s: journal: %v", p.Slug, err)
	}
	t.o.Log.Printf("ticker: %s: upkeep: %s", p.Slug, detail)
}

// clearBlocked finds the project's coordinator and says what keeps it
// from being cleared now; "" when nothing does. At delivery the clear
// itself may still count as queued, and a prompt queued after it lands
// in the fresh conversation: the queue isn't looked at then. own looks
// at the coordinator alone (the user's request), not at what waits in
// the project.
func clearBlocked(p *project.Project, sessions []proto.SessionInfo, hint int, delivery, own bool) (*proto.SessionInfo, string) {
	coord := proto.CoordinatorOf(sessions, p.Slug)
	switch {
	case coord == nil:
		return nil, "no coordinator"
	case coord.State != "idle":
		return coord, "not idle"
	case coord.Queued > 0 && !delivery:
		return coord, "prompt queued"
	case coord.Question != nil:
		return coord, "question open"
	case coord.ContextPercent() < hint:
		return coord, "context below the hint"
	case own:
		return coord, ""
	}
	for _, s := range sessions {
		if s.Project == p.Slug && s.Role == proto.RoleThread && (s.Question != nil || s.State == "blocked") {
			return coord, "thread " + s.Thread + " waits"
		}
	}
	items, err := p.Inbox()
	if err != nil {
		return coord, "inbox: " + err.Error()
	}
	if len(items) > 0 {
		return coord, "inbox not empty"
	}
	recs, err := thread.List(p)
	if err != nil {
		return coord, "threads: " + err.Error()
	}
	for _, r := range recs {
		if r.State == thread.Resolved {
			continue
		}
		if st, err := thread.ReadStatus(p, r.ID); err == nil && st.NeedsYou != "" {
			return coord, "thread " + r.ID + " needs the user"
		}
	}
	return coord, ""
}
