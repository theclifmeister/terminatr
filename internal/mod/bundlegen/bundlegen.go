// Package bundlegen precompiles terminatr's bundled code mods (mods
// design §11): each one's source is its folder in examples/mods, and
// what tm embeds is internal/mod/bundled/<id>: its manifest, naming the
// bundle as its main, and main.js, the bundle esbuild made of its main.
// A bundled mod's host then runs it as is, without esbuild, at once.
//
// `go generate ./internal/mod` writes them; a test in internal/mod fails
// while one is stale.
package bundlegen

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"

	"github.com/theclifmeister/terminatr/internal/modhost"
)

// Code are the bundled code mods' ids: folders of examples/mods.
var Code = []string{"pr-ci-column"}

// Main is a bundled code mod's main in its embedded folder.
const Main = "main.js"

// header starts every generated file.
const header = "Code generated by go generate ./internal/mod from examples/mods/%s; DO NOT EDIT."

var mainRE = regexp.MustCompile(`(?m)^main = "[^"]*"$`)

// Files are bundled code mod id's generated files, by name (mod.toml and
// main.js), from its source in src (examples/mods/<id>).
func Files(src, id string) (map[string][]byte, error) {
	man, err := os.ReadFile(filepath.Join(src, "mod.toml"))
	if err != nil {
		return nil, err
	}
	m := mainRE.FindSubmatchIndex(man)
	if m == nil {
		return nil, fmt.Errorf("%s/mod.toml names no main", id)
	}
	entry := filepath.Join(src, string(bytes.Trim(man[m[0]+len(`main = `):m[1]], `"`)))
	code, _, err := modhost.Bundle(entry)
	if err != nil {
		return nil, err
	}
	head := fmt.Sprintf(header, id)
	man = mainRE.ReplaceAll(man, []byte(`main = "`+Main+`"`))
	return map[string][]byte{
		"mod.toml": append([]byte("# "+head+"\n\n"), man...),
		Main:       []byte("// " + head + "\n" + code),
	}, nil
}

// Write writes every bundled code mod's files from examples (the
// examples/mods folder) into bundled (internal/mod/bundled).
func Write(examples, bundled string) error {
	for _, id := range Code {
		files, err := Files(filepath.Join(examples, id), id)
		if err != nil {
			return fmt.Errorf("%s: %w", id, err)
		}
		dir := filepath.Join(bundled, id)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		for name, b := range files {
			if err := os.WriteFile(filepath.Join(dir, name), b, 0o644); err != nil {
				return err
			}
		}
	}
	return nil
}
